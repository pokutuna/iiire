import AppKit
import ApplicationServices

/// 入力した結果
enum InsertResult: Equatable {
    case pasted      // カーソル位置にペーストした
    case copied      // クリップボードにコピーした (設定どおり)
    case notPasted   // ペーストできず、クリップボードに残した
}

/// 書き起こした文字列をクリップボード経由でカーソル位置にペーストする。
@MainActor
enum TextInserter {
    /// 入力先 (最前面のアプリ) のルールを当てて入力する。
    /// onResult はペーストのキーを送った時点で呼ぶ (クリップボードを戻すのを待たない)
    static func insert(_ text: String, onResult: (InsertResult) -> Void) async {
        let target = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let config = Defaults.outputConfig(for: target)
        Log.info("insert into \(target ?? "?"): output=\(config.output.rawValue) keystroke=\(config.keystroke.rawValue)\(config.customKey.map { " " + $0.displayName } ?? "")")
        await insert(text, config: config, onResult: onResult)
    }

    /// 戻す前のクリップボードの中身と、文字列を置いた後の changeCount
    private typealias Restore = (items: [NSPasteboardItem], changeCount: Int)
    /// まだ戻していないクリップボードの中身。戻す前に次の入力が来たら、これを引き継ぐ
    /// (置いた文字列を元の中身と取り違えない)
    private static var pendingRestore: Restore?
    /// キーを送っている最中の入力。次の入力は、これが送り終えるまで待つ
    /// (送っている途中のキーと、次の入力のクリップボードやキーが混ざらないように)
    private static var sending: Task<Void, Never>?

    static func insert(_ text: String, config: OutputConfig, onResult: (InsertResult) -> Void) async {
        let previous = sending
        let send = Task {
            await previous?.value
            return await paste(text, config: config)
        }
        sending = Task { _ = await send.value }
        let (result, changeCount) = await send.value
        onResult(result)

        guard result == .pasted else { return }
        // ペースト先が読み終えるまで待ってから戻す
        try? await Task.sleep(for: .milliseconds(Defaults.clipboardRestoreDelayMs))
        let pb = NSPasteboard.general
        // その間に誰かがコピーしたか、次の入力が引き継いだ
        guard pb.changeCount == changeCount, let restore = pendingRestore, restore.changeCount == changeCount else { return }
        pendingRestore = nil
        pb.clearContents()
        if !restore.items.isEmpty { pb.writeObjects(restore.items) }
    }

    /// 文字列をクリップボードに置き、ペーストのキーを送る。置いた後の changeCount も返す。
    /// 後で戻す中身は pendingRestore に残す
    private static func paste(_ text: String, config: OutputConfig) async -> (InsertResult, changeCount: Int) {
        let pb = NSPasteboard.general
        let pending = pendingRestore.flatMap { $0.changeCount == pb.changeCount ? $0.items : nil }
        pendingRestore = nil

        guard config.output != .clipboard else {
            put(text, on: pb, transient: false)
            return (.copied, pb.changeCount)
        }

        let saved = config.output == .paste ? (pending ?? snapshot(pb)) : nil
        // 元に戻すなら一時的な中身なので、履歴を取るアプリに残さないよう伝える
        put(text, on: pb, transient: saved != nil)
        let changeCount = pb.changeCount
        pendingRestore = saved.map { Restore($0, changeCount) }
        let target = NSWorkspace.shared.frontmostApplication?.processIdentifier

        try? await Task.sleep(for: .milliseconds(50))
        // 誰かがコピーしたか、最前面のアプリが変わったら送らない (別の中身や別のアプリにキーを送らない)。
        // キーを送る間にも変わりうるので、ペーストのキーを押す直前にも確かめる
        let unchanged = {
            pb.changeCount == changeCount && NSWorkspace.shared.frontmostApplication?.processIdentifier == target
        }
        guard await sendPaste(config, while: unchanged) else {
            // 送れなければクリップボードに残す。戻さないので、履歴にも残してよいものとして置き直す
            Log.info("paste skipped (text left in clipboard)")
            if pb.changeCount == changeCount {
                pendingRestore = nil
                if saved != nil { put(text, on: pb, transient: false) }
            }
            return (.notPasted, changeCount)
        }
        return (.pasted, changeCount)
    }

    /// iiire が送ったキー入力の目印 (eventSourceUserData)。自分のホットキーとして拾わないために使う
    private nonisolated static let eventMarker: Int64 = 0x494952 // "IIR"

    nonisolated static func isSynthesized(_ e: NSEvent) -> Bool {
        e.cgEvent?.getIntegerValueField(.eventSourceUserData) == eventMarker
    }

    static var isTrusted: Bool { AXIsProcessTrusted() }

    static func requestAccessibility() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    /// nspasteboard.org の慣習の目印。履歴を取るアプリ (Maccy, Raycast など) が見る
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// 文字列を置く。置いたアプリを示し、transient なら履歴に残さなくてよいと示す
    static func put(_ text: String, on pb: NSPasteboard, transient: Bool) {
        pb.clearContents()
        pb.setString(text, forType: .string)
        if let id = Bundle.main.bundleIdentifier { pb.setString(id, forType: sourceType) }
        if transient {
            pb.setData(Data(), forType: transientType)
            pb.setData(Data(), forType: autoGeneratedType)
        }
    }

    private static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func sendPaste(_ config: OutputConfig, while canSend: () -> Bool) async -> Bool {
        guard AXIsProcessTrusted() else {
            Log.info("paste: accessibility not granted")
            return false
        }
        guard !sendsHotkey(config) else {
            Log.info("paste: the key to send is the recording hotkey")
            return false
        }
        let interval = Defaults.pasteKeyIntervalMs
        switch config.keystroke {
        case .rightCommand:
            // 右 ⌘ を押して、物理的に押されている左 ⌘ と干渉しないようにする。
            // flags は ⌘ だけにし、左右のビットは付けない (VoiceInk と同じ送り方)
            return await postKey(0x09, modifiers: [ModifierKey(code: 0x36, flags: .maskCommand)], interval: interval, while: canSend)
        case .leftCommand:
            return await postKey(0x09, modifiers: [.leftCommand], interval: interval, while: canSend)
        case .appleScript:
            return canSend() && pasteWithAppleScript()
        case .custom:
            guard let key = config.customKey else { return false }
            return await postKey(key.keyCode, modifiers: ModifierKey.left(key.modifierFlags), interval: interval, while: canSend)
        }
    }

    /// 送る修飾キー。flags にはデバイスごとの左右のビットも入れる (左右を区別するアプリはこれを見る)
    private struct ModifierKey {
        let code: CGKeyCode
        let flags: CGEventFlags

        static func left(_ code: CGKeyCode, _ mask: CGEventFlags, _ device: Int32) -> ModifierKey {
            ModifierKey(code: code, flags: [mask, CGEventFlags(rawValue: UInt64(device))])
        }
        static let leftControl = left(0x3B, .maskControl, NX_DEVICELCTLKEYMASK)
        static let leftOption = left(0x3A, .maskAlternate, NX_DEVICELALTKEYMASK)
        static let leftShift = left(0x38, .maskShift, NX_DEVICELSHIFTKEYMASK)
        static let leftCommand = left(0x37, .maskCommand, NX_DEVICELCMDKEYMASK)

        /// ⌃⌥⇧⌘ を左側のキーとして押す
        static func left(_ flags: NSEvent.ModifierFlags) -> [ModifierKey] {
            [(NSEvent.ModifierFlags.control, leftControl), (.option, leftOption), (.shift, leftShift), (.command, leftCommand)]
                .filter { flags.contains($0.0) }.map(\.1)
        }
    }

    /// 送るキーが録音のホットキーと同じか (同じなら、自分の送ったキーで録音が始まってしまう)
    private static func sendsHotkey(_ config: OutputConfig) -> Bool {
        let hotkey = Defaults.shortcut
        guard hotkey.kind == .combo else { return false }
        switch config.keystroke {
        case .custom:
            guard let key = config.customKey else { return false }
            return hotkey.keyCode == key.keyCode && hotkey.modifierFlags == key.modifierFlags
        case .appleScript:
            // 文字 "v" を打つので、どのキーになるかは配列による。ホットキーを記録したときの文字で比べる
            return hotkey.modifierFlags == .command && hotkey.keyLabel == "V"
        default:
            return hotkey.modifierFlags == .command && hotkey.keyCode == 0x09
        }
    }

    /// 修飾キーを順に押し、キーを押して離し、修飾キーを逆順に離す。
    /// 続けて送ると取りこぼすアプリがあるので、イベントの間を interval ms 空ける。
    /// キーを押す直前に canSend が false なら、キーは押さずに修飾キーだけ離して false を返す
    private static func postKey(_ key: CGKeyCode, modifiers: [ModifierKey], interval: Int,
                                while canSend: () -> Bool) async -> Bool {
        let src = CGEventSource(stateID: .privateState)
        src?.userData = eventMarker
        func event(_ code: CGKeyCode, down: Bool, _ flags: CGEventFlags) -> CGEvent? {
            let e = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: down)
            e?.flags = flags
            return e
        }
        var flags: CGEventFlags = []
        var press: [CGEvent] = [], release: [CGEvent] = []
        for m in modifiers {
            flags.formUnion(m.flags)
            guard let e = event(m.code, down: true, flags) else { return false }
            press.append(e)
        }
        guard let keyDown = event(key, down: true, flags), let keyUp = event(key, down: false, flags) else { return false }
        for m in modifiers.reversed() {
            flags.subtract(m.flags)
            guard let e = event(m.code, down: false, flags) else { return false }
            release.append(e)
        }

        func post(_ events: [CGEvent]) async {
            for e in events {
                if interval > 0 { try? await Task.sleep(for: .milliseconds(interval)) }
                e.post(tap: .cghidEventTap)
            }
        }
        guard canSend() else { return false }
        await post(press)
        let ok = canSend()
        await post(ok ? [keyDown, keyUp] + release : release)
        return ok
    }

    /// System Events に ⌘V を打ってもらう。文字 "v" を指定するので、多くのキー配列でそのまま使える。
    /// 初回は macOS が「System Events の制御」の許可を求める
    private static let pasteScript = NSAppleScript(source: #"tell application "System Events" to keystroke "v" using command down"#)

    private static func pasteWithAppleScript() -> Bool {
        guard let pasteScript else { return false }
        var error: NSDictionary?
        pasteScript.executeAndReturnError(&error)
        if let error {
            // -1743: オートメーションの許可がない
            Log.info("AppleScript paste failed: \(error[NSAppleScript.errorNumber] ?? "?") \(error[NSAppleScript.errorMessage] ?? "")")
            return false
        }
        return true
    }
}
