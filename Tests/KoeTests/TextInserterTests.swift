import AppKit
import XCTest
@testable import Koe

/// クリップボードに置く目印を確かめる。一般のクリップボードを汚さないよう、専用のものを使う
@MainActor
final class TextInserterTests: XCTestCase {
    private var pb: NSPasteboard!

    override func setUp() async throws {
        pb = NSPasteboard(name: NSPasteboard.Name("koe-test-\(UUID().uuidString)"))
    }

    override func tearDown() async throws {
        pb.releaseGlobally()
    }

    private func types() -> Set<String> {
        Set((pb.types ?? []).map(\.rawValue))
    }

    func testTransientMarksForHistoryApps() {
        TextInserter.put("こんにちは", on: pb, transient: true)
        XCTAssertEqual(pb.string(forType: .string), "こんにちは")
        XCTAssertTrue(types().isSuperset(of: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]))
    }

    func testKeptTextIsNotTransient() {
        TextInserter.put("こんにちは", on: pb, transient: false)
        XCTAssertEqual(pb.string(forType: .string), "こんにちは")
        XCTAssertTrue(types().isDisjoint(with: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]))
    }
}
